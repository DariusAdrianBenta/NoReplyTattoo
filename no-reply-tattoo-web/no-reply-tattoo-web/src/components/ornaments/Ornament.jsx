export const ORNAMENT_NAMES = Object.keys(SHAPES)

export default function Ornament({
  name,
  size = 40,
  draw = false,
  strokeWidth = 1.4,
  className = '',
  style,
  delay,
  title,
}) {
  const ref = useRef(null)
  const inView = useInView(ref, { once: true, disabled: !draw })
  const shape = SHAPES[name]
  if (!shape) return null

  const [, , w, h] = shape.vb.split(' ').map(Number)
  const height = (size * h) / w
  const cls = ['ornament', `ornament--${name}`, draw && 'draw', draw && inView && 'is-in', className]
    .filter(Boolean)
    .join(' ')

  return (
    <svg
      ref={ref}
      className={cls}
      width={size}
      height={height}
      viewBox={shape.vb}
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      style={{ ...style, ...(delay != null ? { '--delay': `${delay}s` } : null) }}
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
      focusable="false"
    >
      {title && <title>{title}</title>}
      {shape.paths.map((d, i) => (
        <path key={i} d={d} pathLength={draw ? 1 : undefined} />
      ))}
    </svg>
  )
}
